//! Regression tests from the stroke-expansion spike (ADR 0019 S1/S2, #425):
//! bands of a round-nib stroke along a 330° arc, whose sides are biarcs of
//! fitted cubics. Two bugs lost the whole result:
//!
//! * `merge_carriers` merged near-identical circles (within 10 × SNAP) but
//!   kept the first circle, so the merged arc ended ~µm off the shared vertex;
//!   the next boolean saw a gap and dropped the loop.
//! * a 1 µm arc edge left by two near-tangent arcs crossing next to a shared
//!   vertex was misclassified (its probes sit ≤ 0.1 µm off), leaving an open
//!   chain that `trace` dropped with its loop.

#![allow(
    clippy::unwrap_used,
    clippy::excessive_precision,
    clippy::approx_constant
)]

use locus_geom::Vec2;
use locus_region::{Area, BoolOp, Edge, Loop, SNAP, Seg, boolean, union_all};

fn v(x: f64, y: f64) -> Vec2 {
    Vec2::new(x, y)
}

fn line(a: Vec2, b: Vec2) -> Seg {
    Seg::Line { a, b }
}

fn arc(center: Vec2, radius: f64, start: f64, sweep: f64) -> Seg {
    Seg::Arc {
        center,
        radius,
        start,
        sweep,
    }
}

fn area(loops: Vec<Vec<Seg>>) -> Area {
    Area {
        loops: loops
            .into_iter()
            .map(|segs| Loop {
                edges: segs
                    .into_iter()
                    .map(|seg| Edge { seg, source: 1 })
                    .collect(),
            })
            .collect(),
    }
}

