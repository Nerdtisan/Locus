/// Every loop closes: each edge ends within SNAP of where the next starts.
fn assert_closed(a: &Area) {
    for l in &a.loops {
        let n = l.edges.len();
        for i in 0..n {
            let (e, f) = (&l.edges[i].seg, &l.edges[(i + 1) % n].seg);
            assert!(
                e.end().distance(f.start()) <= SNAP,
                "gap {:e} between {e:?} and {f:?}",
                e.end().distance(f.start())
            );
        }
    }
}

#[test]
fn normalised_bands_stay_closed_and_reunite() {
    for p in pieces() {
        let once = boolean(&p, &Area::default(), BoolOp::Union);
        assert_closed(&once);
        let twice = boolean(&once, &Area::default(), BoolOp::Union);
        assert!(
            (twice.area() - once.area()).abs() < 1e-6,
            "re-union changed the area: {} -> {}",
            once.area(),
            twice.area()
        );
    }
}

#[test]
fn union_of_stroke_bands_never_loses_area() {
    let norm: Vec<Area> = pieces()
        .iter()
        .map(|p| boolean(p, &Area::default(), BoolOp::Union))
        .collect();
    let mut acc = Area::default();
    for p in &norm {
        let next = boolean(&acc, p, BoolOp::Union);
        assert!(
            next.area() + 1e-6 >= acc.area().max(p.area()),
            "union lost area: {} ∪ {} -> {}",
            acc.area(),
            p.area(),
            next.area()
        );
        assert_closed(&next);
        acc = next;
    }
    // The stroke: a 330° ring, r 3..7, closed by its round ends (the 30°
    // gap is narrower than the nib), so one outer loop and one hole.
    let all = union_all(&norm);
    assert_eq!(all.loops.len(), 2, "{all:?}");
    // One union or a chain of them: the same shape, up to vertex snapping
    // (perimeter ~60 mm × SNAP).
    assert!(
        (all.area() - acc.area()).abs() < 1e-4,
        "{} vs {}",
        all.area(),
        acc.area()
    );
}

